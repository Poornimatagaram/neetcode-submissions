def print_first_char(word: str) -> None:
    firstchar = word[0]
    print(firstchar)

def print_second_char(word: str) -> None:
    secondchar = word[1]
    print(secondchar)

def print_last_char(word: str) -> None:
    lastchar = word[-1]
    print(lastchar)


